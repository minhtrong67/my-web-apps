// Regenerates src/components/ui/iconMap.js from the Material Symbols (Rounded, weight 400) SVG set.
// Usage: node scripts/gen-icons.mjs
// Keys are the app's icon names; values map to a Material Symbols file name (differs only where the
// symbol was renamed). Only the path data is emitted, so there is no runtime SVG parsing.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'node_modules/@material-symbols/svg-400/rounded');

const ICONS = `account_balance account_balance_wallet account_box add add_circle apps arrow_back arrow_downward arrow_forward
arrow_upward attach_money autorenew backup badge bar_chart bolt brightness_auto business_center calendar_month category check
check_circle chevron_left chevron_right close code colorize credit_card currency_exchange dark_mode delete description diamond
donut_large download edit edit_note error event event_busy favorite filter_alt_off format_size help image info language light_mode
lock lock_reset logout mail mark_email_read menu notifications notifications_active notifications_off open_in_new palette
pause_circle payments person picture_as_pdf pie_chart play_circle qr_code_2 real_estate_agent receipt_long remove restart_alt
rocket savings schedule search search_off settings shield show_chart space_dashboard star summarize swap_vert sync_alt table_view
translate trending_down trending_up tune upload_file visibility visibility_off warning wifi_off`.split(/\s+/);

// app name -> Material Symbols file name where they differ
const ALIAS = {
  card_giftcard: 'redeem',
  expand_more: 'keyboard_arrow_down',
  expand_less: 'keyboard_arrow_up',
  install_mobile: 'mobile_arrow_down',
  smartphone: 'mobile',
  sort_az: 'sort_by_alpha',
  sort_za: 'sort_by_alpha',
  sort_desc: 'sort',
  auto_awesome: 'stars',
};
const ALL = [...ICONS, ...Object.keys(ALIAS)].sort();
// Icons that have a filled "selected" form (navigation, state)
const FILLED = new Set(['space_dashboard', 'receipt_long', 'category', 'account_balance_wallet', 'bar_chart', 'settings', 'savings',
  'event', 'autorenew', 'check_circle', 'notifications', 'notifications_active', 'person', 'pie_chart', 'calendar_month', 'star', 'favorite']);

const d = (file) => /<path d="([^"]+)"/.exec(readFileSync(join(dir, file), 'utf8'))[1];
const lines = ALL.map((name) => {
  const file = ALIAS[name] || name;
  const fill = FILLED.has(name) ? `, ${JSON.stringify(d(`${file}-fill.svg`))}` : '';
  return `  ${name}: [${JSON.stringify(d(`${file}.svg`))}${fill}],`;
});

writeFileSync(join(root, 'src/components/ui/iconMap.js'),
`// GENERATED by scripts/gen-icons.mjs - do not edit by hand.
// Material Symbols Rounded (wght 400), viewBox "0 -960 960 960". [outlined path, filled path?]
const ICON_MAP = {
${lines.join('\n')}
};

export default ICON_MAP;
`);
console.log(`wrote ${ALL.length} icons`);
