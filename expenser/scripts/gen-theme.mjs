// Generates src/theme/colors.css (default Material 3 Expressive green scheme, light + dark)
// from the seed colour with Google's material-color-utilities.
// Usage: node scripts/gen-theme.mjs
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'node_modules/.cache/gen-theme.mjs');
await build({ entryPoints: [join(root, 'src/theme/scheme.js')], bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error' });
const { generateScheme, SEED, schemeToCss } = await import(pathToFileURL(out).href);
const s = generateScheme(SEED);
const block = (sel, r) => `${sel} {\n${schemeToCss(r).split(';').filter(Boolean).map((l) => `  ${l};`).join('\n')}\n}`;
writeFileSync(join(root, 'src/theme/colors.css'),
`/* GENERATED by scripts/gen-theme.mjs from seed ${SEED} (Material 3 Expressive, Vibrant). Do not edit by hand. */
${block(':root', s.light)}

${block('.dark', s.dark)}
`);
console.log('colors.css written');
